export type TransactionType = 'income' | 'expense';

export type SpendingNature = 'essential' | 'lifestyle' | 'savings';

export interface Category {
  id: string;
  name: string;
  type: TransactionType;
  nature: SpendingNature;
  icon: string;
  color: string;
}

export interface Transaction {
  id: string;
  date: string; // YYYY-MM-DD
  description: string;
  amount: number;
  type: TransactionType;
  categoryId: string;
  nature: SpendingNature;
  paymentMethod: 'pix' | 'credit' | 'debit' | 'cash' | 'transfer' | 'other';
  status: 'completed' | 'pending';
  notes?: string;
  recurring?: boolean;
}

export type AutoRuleType = 'emergency_fund' | 'rule_50_30_20' | 'retirement' | 'custom';

export interface SavingsGoal {
  id: string;
  title: string;
  category: string;
  targetAmount: number;
  currentAmount: number;
  deadline?: string; // YYYY-MM-DD
  monthlyTargetContribution: number;
  autoRuleType: AutoRuleType;
  isAutoGenerated: boolean;
  color: string;
  icon: string;
  notes?: string;
  estimatedMonthsRemaining?: number;
}

export interface MonthlyBudgetRule503020 {
  income: number;
  
  // 50% Necessidades
  needsIdeal: number;
  needsActual: number;
  needsDiff: number;
  
  // 30% Desejos
  wantsIdeal: number;
  wantsActual: number;
  wantsDiff: number;
  
  // 20% Poupança & Investimentos
  savingsIdeal: number;
  savingsActual: number;
  savingsDiff: number;
  
  healthScore: 'healthy' | 'moderate' | 'critical';
  recommendations: string[];
}

export interface PythonExecutionResult {
  output: string;
  logs: string[];
  executionTimeMs: number;
  engine: 'pyodide' | 'fallback_engine';
  success: boolean;
  computedStats?: {
    income: number;
    expenses: number;
    savings: number;
    emergencyTarget: number;
    recommendedMonthlySavings: number;
  };
}
